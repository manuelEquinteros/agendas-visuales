CREATE TABLE agenda_visual (
    id_agenda BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    tipo_agenda VARCHAR(20) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_modificacion TIMESTAMP NOT NULL,

    CONSTRAINT chk_agenda_visual_tipo
        CHECK (tipo_agenda IN ('DIARIA', 'SEMANAL'))
);

CREATE TABLE dia_agenda (
    id_dia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_agenda BIGINT NOT NULL,
    fecha DATE NOT NULL,
    orden INTEGER NOT NULL,

    CONSTRAINT fk_dia_agenda_agenda
        FOREIGN KEY (id_agenda)
        REFERENCES agenda_visual(id_agenda)
        ON DELETE CASCADE
);

CREATE TABLE pictograma (
    id_arasaac BIGINT PRIMARY KEY,
    descripcion VARCHAR(200) NOT NULL,
    url_imagen VARCHAR(500) NOT NULL
);

CREATE TABLE actividad_agenda (
    id_actividad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_dia BIGINT NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    descripcion VARCHAR(500),
    orden INTEGER NOT NULL,
    hora_inicio TIME,
    hora_fin TIME,
    acompaniante VARCHAR(150),
    concepto_visual VARCHAR(150) NOT NULL,
    id_arasaac BIGINT,

    CONSTRAINT fk_actividad_agenda_dia
        FOREIGN KEY (id_dia)
        REFERENCES dia_agenda(id_dia)
        ON DELETE CASCADE,

    CONSTRAINT fk_actividad_agenda_pictograma
        FOREIGN KEY (id_arasaac)
        REFERENCES pictograma(id_arasaac)
        ON DELETE SET NULL
);

CREATE INDEX idx_dia_agenda_id_agenda
    ON dia_agenda(id_agenda);

CREATE INDEX idx_actividad_agenda_id_dia
    ON actividad_agenda(id_dia);

CREATE INDEX idx_actividad_agenda_id_arasaac
    ON actividad_agenda(id_arasaac);